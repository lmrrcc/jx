import java.io.IOException;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.ArrayList;
import java.util.LinkedHashMap;
import java.util.List;
import java.util.Map;
import java.util.Set;
import java.util.TreeSet;
import java.util.regex.Matcher;
import java.util.regex.Pattern;

/**
 * Generates the bench cases that render every HTML and SVG element, every attribute name
 * and every event handler name React DOM knows, once for the React reference and once for
 * JX, from the same markup.
 *
 * <p>Attribute and event names are read from the tables inside the installed React DOM
 * development build, so the cases follow the React version in use. Element names are the lists below.
 * Run {@code java tools/GenerateDomTables.java} after changing React or this file;
 * {@code --check} fails when the generated files on disk differ.
 */
public final class GenerateDomTables {
    private static final String REACT_DOM = "node_modules/react-dom/cjs/react-dom-client.development.js";
    private static final String REFERENCE = "tests/conformance/reference/cases/dom-tables.jsx";
    private static final String JX_CASES = "tests/conformance/src/main/jx/jx/conformance/cases/";
    private static final String NOTICE = "Generated by tools/GenerateDomTables.java; do not edit.";
    /** JX components are kept small: one render method must stay far below the JVM method size limit. */
    private static final int PART_SIZE = 50;

    /** HTML elements that may appear anywhere in flow content, each rendered empty. */
    private static final List<String> HTML_FLOW = List.of("a", "abbr", "address", "article", "aside", "b", "bdi", "bdo",
            "blockquote", "br", "button", "canvas", "cite", "code", "data", "datalist", "del", "dfn", "dialog", "div", "em",
            "embed", "footer", "form", "h1", "h2", "h3", "h4", "h5", "h6", "header", "hgroup", "hr", "i", "iframe", "img",
            "input", "ins", "kbd", "label", "main", "mark", "menu", "meter", "nav", "noscript", "ol", "output", "p", "pre",
            "progress", "q", "s", "samp", "search", "section", "slot", "small", "span", "strong", "sub", "sup", "template",
            "textarea", "time", "u", "var", "wbr");
    /** HTML elements that are only valid inside a particular parent, in that structure. */
    private static final List<String> HTML_STRUCTURES = List.of(
            "<table><caption /><colgroup><col /></colgroup><thead><tr><th /></tr></thead><tbody><tr><td /></tr></tbody><tfoot /></table>",
            "<ul><li /></ul>",
            "<dl><dt /><dd /></dl>",
            "<select><optgroup><option /></optgroup></select>",
            "<fieldset><legend /></fieldset>",
            "<details><summary /></details>",
            "<figure><figcaption /></figure>",
            "<ruby><rt /><rp /></ruby>",
            "<audio><source /><track /></audio>",
            "<video />",
            "<map><area /></map>",
            "<object />",
            "<picture><source /><img /></picture>");
    /** SVG elements, rendered inside one svg element. */
    private static final List<String> SVG = List.of("a", "animate", "animateMotion", "animateTransform", "circle", "clipPath",
            "defs", "desc", "ellipse", "feBlend", "feColorMatrix", "feComponentTransfer", "feComposite", "feConvolveMatrix",
            "feDiffuseLighting", "feDisplacementMap", "feDistantLight", "feDropShadow", "feFlood", "feFuncA", "feFuncB",
            "feFuncG", "feFuncR", "feGaussianBlur", "feImage", "feMerge", "feMergeNode", "feMorphology", "feOffset",
            "fePointLight", "feSpecularLighting", "feSpotLight", "feTile", "feTurbulence", "filter", "foreignObject", "g",
            "image", "line", "linearGradient", "marker", "mask", "metadata", "mpath", "path", "pattern", "polygon",
            "polyline", "radialGradient", "rect", "set", "stop", "switch", "symbol", "text", "textPath", "tspan", "use", "view");

    /** Attributes React treats as true or false; they are passed {@code true}. */
    private static final Set<String> BOOLEAN = Set.of("allowFullScreen", "async", "autoPlay", "controls", "default", "defer",
            "disabled", "disablePictureInPicture", "disableRemotePlayback", "formNoValidate", "hidden", "loop", "noModule",
            "noValidate", "open", "playsInline", "readOnly", "required", "reversed", "scoped", "seamless", "itemScope",
            "inert", "capture", "download");
    /** Attributes for which the browser rejects the common sample value "2". */
    private static final Map<String, String> SAMPLES = Map.of("transform", "scale(2)");
    /** Names in React's table that are not plain attributes; each has a dedicated case or API. */
    private static final Map<String, String> SKIPPED = skipped();

    private static Map<String, String> skipped() {
        Map<String, String> map = new LinkedHashMap<>();
        map.put("children", "the children of an element, not an attribute");
        map.put("dangerouslySetInnerHTML", "raw HTML; case raw-html");
        map.put("innerHTML", "not a React property; React warns and names dangerouslySetInnerHTML");
        map.put("style", "takes a Style value; case attributes");
        map.put("value", "form control state; cases controlled-input and uncontrolled-inputs");
        map.put("defaultValue", "form control state; case uncontrolled-inputs");
        map.put("checked", "form control state; case checkbox");
        map.put("defaultChecked", "form control state; case uncontrolled-inputs");
        map.put("selected", "form control state; case choice-inputs");
        map.put("multiple", "form control state; case choice-inputs");
        map.put("muted", "media element state; case media-events");
        map.put("autoFocus", "focus behavior, not an attribute; React calls focus on mount");
        map.put("suppressContentEditableWarning", "a React development switch");
        map.put("suppressHydrationWarning", "a React development switch");
        map.put("action", "URL or function; case form-actions");
        map.put("formAction", "URL or function; case form-actions");
        return map;
    }

    private GenerateDomTables() {}

    public static void main(String[] arguments) throws IOException {
        boolean check = arguments.length == 1 && arguments[0].equals("--check");
        if (arguments.length > (check ? 1 : 0)) {
            System.err.println("Usage: java tools/GenerateDomTables.java [--check]");
            System.exit(2);
        }
        Path root = Path.of("").toAbsolutePath();
        Set<String> names = attributeNames(Files.readString(root.resolve(REACT_DOM), StandardCharsets.UTF_8));
        List<Event> events = events(Files.readString(root.resolve(REACT_DOM), StandardCharsets.UTF_8));
        List<String> attributes = names.stream().filter(name -> !SKIPPED.containsKey(name)).toList();
        for (String name : SKIPPED.keySet()) {
            if (!names.contains(name)) throw new IOException("Skipped name is not in React's table any more: " + name);
        }

        Map<String, String> files = new LinkedHashMap<>();
        List<String> elementParts = new ArrayList<>();
        elementParts.add("<section data-group=\"html\">" + selfClosing(HTML_FLOW) + String.join("", HTML_STRUCTURES) + "</section>");
        elementParts.add("<svg data-group=\"svg\">" + selfClosing(SVG) + "</svg>");
        List<String> attributeParts = new ArrayList<>();
        for (int start = 0; start < attributes.size(); start += PART_SIZE) {
            List<String> slice = attributes.subList(start, Math.min(start + PART_SIZE, attributes.size()));
            StringBuilder html = new StringBuilder("<section data-group=\"html-attributes\">");
            StringBuilder svg = new StringBuilder("<svg data-group=\"svg-attributes\">");
            for (String name : slice) {
                String value = BOOLEAN.contains(name) ? "={true}" : "=\"" + SAMPLES.getOrDefault(name, "2") + "\"";
                html.append("<div ").append(name).append(value).append(" />");
                svg.append("<g ").append(name).append(value).append(" />");
            }
            attributeParts.add(html.append("</section>").toString());
            attributeParts.add(svg.append("</svg>").toString());
        }

        // Each handler name sits on a plain element and on a media element, because React
        // listens for media events only on media elements.
        List<String> referenceEvents = new ArrayList<>();
        List<String> jxEvents = new ArrayList<>();
        for (int start = 0; start < events.size(); start += PART_SIZE / 2) {
            List<Event> slice = events.subList(start, Math.min(start + PART_SIZE / 2, events.size()));
            StringBuilder referenceMarkup = new StringBuilder("<section data-group=\"events\">");
            StringBuilder jxMarkup = new StringBuilder("<section data-group=\"events\">");
            for (Event event : slice) {
                for (String tag : List.of("div", "video")) {
                    String open = "<" + tag + " data-event=\"" + event.name() + "\" on" + event.name() + "={";
                    referenceMarkup.append(open).append("() => log('").append(event.name()).append("')}");
                    jxMarkup.append(open).append("event -> Bench.log(\"").append(event.name()).append("\")}");
                    if (event.capture()) {
                        referenceMarkup.append(" on").append(event.name()).append("Capture={() => log('").append(event.name()).append(" capture')}");
                        jxMarkup.append(" on").append(event.name()).append("Capture={event -> Bench.log(\"").append(event.name()).append(" capture\")}");
                    }
                    referenceMarkup.append(" />");
                    jxMarkup.append(" />");
                }
            }
            referenceEvents.add(referenceMarkup.append("</section>").toString());
            jxEvents.add(jxMarkup.append("</section>").toString());
        }

        StringBuilder reference = new StringBuilder("// " + NOTICE + "\n// Every HTML and SVG element, every attribute name in React DOM's table ("
                + attributes.size() + " rendered, " + SKIPPED.size() + " covered elsewhere)\n// and every event handler name ("
                + events.size() + ").\nimport { log } from '../bench.js';\n\n");
        reference.append(referenceComponent("DomElements", elementParts));
        reference.append(referenceComponent("DomAttributes", attributeParts));
        reference.append(referenceComponent("DomEvents", referenceEvents));
        files.put(REFERENCE, reference.toString());
        jx(files, "DomElements", "dom-elements: every HTML and SVG element renders as in React", elementParts);
        jx(files, "DomAttributes", "dom-attributes: every attribute name React knows renders as in React", attributeParts);
        jx(files, "DomEvents", "dom-events: every event handler name React knows is called as in React", jxEvents);

        boolean stale = false;
        for (Map.Entry<String, String> file : files.entrySet()) {
            Path target = root.resolve(file.getKey());
            String current = Files.exists(target) ? Files.readString(target, StandardCharsets.UTF_8) : null;
            if (file.getValue().equals(current)) continue;
            if (check) {
                System.err.println("FAIL: " + file.getKey() + " is not what the generator produces; run java tools/GenerateDomTables.java");
                stale = true;
            } else {
                Files.createDirectories(target.getParent());
                Files.writeString(target, file.getValue(), StandardCharsets.UTF_8);
                System.out.println("Wrote " + file.getKey());
            }
        }
        if (stale) System.exit(1);
        System.out.printf("PASS: %d HTML and %d SVG elements, %d attribute names (%d covered elsewhere), %d event names, %d files.%n",
                HTML_FLOW.size() + count(HTML_STRUCTURES), SVG.size(), attributes.size(), SKIPPED.size(), events.size(), files.size());
    }

    /** The React property names of React DOM's own table of known attributes. */
    static Set<String> attributeNames(String source) throws IOException {
        int start = source.indexOf("possibleStandardNames = {");
        int end = start < 0 ? -1 : source.indexOf('}', start);
        if (end < 0) throw new IOException("React DOM's attribute table was not found in " + REACT_DOM);
        Set<String> names = new TreeSet<>();
        Matcher entry = Pattern.compile(":\\s*\"([A-Za-z][A-Za-z0-9]*)\"").matcher(source.substring(start, end));
        while (entry.find()) names.add(entry.group(1));
        if (names.size() < 300) throw new IOException("React DOM's attribute table looks incomplete: " + names.size() + " names");
        return names;
    }

    /** An event as React names it without the "on" prefix; enter and leave events have no capture form. */
    record Event(String name, boolean capture) {}

    /** The event handler names React DOM registers, read from its registration calls. */
    static List<Event> events(String source) throws IOException {
        Map<String, Boolean> found = new java.util.TreeMap<>();
        Matcher simple = Pattern.compile("simpleEventPluginEvents =\\s*\"([^\"]+)\"").matcher(source);
        if (!simple.find()) throw new IOException("React DOM's event list was not found in " + REACT_DOM);
        for (String name : simple.group(1).split(" ")) found.put(Character.toUpperCase(name.charAt(0)) + name.substring(1), true);
        Matcher twoPhase = Pattern.compile("register(?:TwoPhaseEvent\\(\\s*|SimpleEvent\\(\\s*[^,]+,\\s*)\"on([A-Za-z]+)\"").matcher(source);
        while (twoPhase.find()) found.put(twoPhase.group(1), true);
        Matcher direct = Pattern.compile("registerDirectEvent\\(\\s*\"on([A-Za-z]+)\"").matcher(source);
        while (direct.find()) found.put(direct.group(1), false);
        if (found.size() < 80) throw new IOException("React DOM's event list looks incomplete: " + found.size() + " names");
        List<Event> events = new ArrayList<>();
        found.forEach((name, capture) -> events.add(new Event(name, capture)));
        return events;
    }

    private static String selfClosing(List<String> tags) {
        StringBuilder markup = new StringBuilder();
        for (String tag : tags) markup.append('<').append(tag).append(" />");
        return markup.toString();
    }

    private static int count(List<String> structures) {
        int total = 0;
        for (String structure : structures) {
            Matcher open = Pattern.compile("<[a-z]").matcher(structure);
            while (open.find()) total++;
        }
        return total;
    }

    private static String referenceComponent(String name, List<String> parts) {
        StringBuilder text = new StringBuilder("export function " + name + "() {\n  return (\n    <main>\n");
        for (String part : parts) text.append("      ").append(part).append('\n');
        return text.append("    </main>\n  );\n}\n\n").toString();
    }

    /** One root component and one component per part, with the markup of the reference. */
    private static void jx(Map<String, String> files, String name, String title, List<String> parts) {
        StringBuilder root = new StringBuilder(header(name, "Case " + title + "."));
        root.append("        return (\n            <main>\n");
        for (int index = 0; index < parts.size(); index++) {
            String part = name + "Part" + (index + 1);
            root.append("                <").append(part).append(" />\n");
            files.put(JX_CASES + part + ".jx", header(part, "Part " + (index + 1) + " of " + name + ".")
                    + "        return " + parts.get(index) + ";\n    }\n}\n");
        }
        files.put(JX_CASES + name + ".jx", root.append("            </main>\n        );\n    }\n}\n").toString());
    }

    private static String header(String name, String description) {
        return "// " + NOTICE + "\npackage jx.conformance.cases;\n\nimport jx.Component;\nimport jx.View;\n"
                + (name.startsWith("DomEventsPart") ? "import jx.conformance.Bench;\n" : "") + "\n/** " + description
                + " */\n@Component\npublic final class " + name + " {\n    public static View render() {\n";
    }
}
